# Общий фильтр списка подсетей Telegram. Подключается через `.`, как records.sh
# в соседнем проекте; сам не запускается.
#
# Список уходит в правила файрвола и перенаправляет трафик устройств сети на
# демон, поэтому по сети (и из файла на диске) принимается только то, что
# похоже на публичную подсеть дата-центра. Всё остальное отбрасывается молча:
# страница с ошибкой, подмена, мусор и, главное, диапазоны, которые никак не
# могут быть Telegram.

# valid_subnets читает строки со stdin и печатает годные IPv4-подсети:
#   - формат a.b.c.d/N, каждая часть до 255;
#   - префикс от /16 до /32: короче — это уже «половина интернета», а не
#     дата-центр;
#   - не частные, не служебные и не мультикаст-адреса: 0/8, 10/8, 100.64/10,
#     127/8, 169.254/16, 172.16/12, 192.168/16, 224/4 и выше.
valid_subnets() {
	awk '
		function ok(s,    a, o, p, i, o1, o2) {
			if (s !~ /^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+\/[0-9]+$/) return 0
			split(s, a, "/")
			p = a[2] + 0
			split(a[1], o, ".")
			for (i = 1; i <= 4; i++)
				if (length(o[i]) > 3 || o[i] + 0 > 255) return 0
			if (p < 16 || p > 32) return 0
			o1 = o[1] + 0
			o2 = o[2] + 0
			if (o1 == 0 || o1 == 10 || o1 == 127 || o1 >= 224) return 0
			if (o1 == 169 && o2 == 254) return 0
			if (o1 == 172 && o2 >= 16 && o2 <= 31) return 0
			if (o1 == 192 && o2 == 168) return 0
			if (o1 == 100 && o2 >= 64 && o2 <= 127) return 0
			return 1
		}
		{ gsub(/[ \t\r]/, ""); if (ok($0)) print }
	'
}
